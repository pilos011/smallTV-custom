"""Emit the IATA code to Korean airport name table.

Same shape as gen_airlines.py, and for the same reason: the table and every
string in it are PROGMEM, and the lookup copies into the caller's buffer. A
PROGMEM table holding pointers to plain literals leaves the literals in DRAM,
which is how 784 bytes of static RAM went missing once already.

Every syllable is checked against the Small font set before a name is emitted,
so a name can never silently lose a character. The labels are drawn at text
size 1, which uiKind() maps to Kind::Small - checking the Large set here would
prove nothing.
"""
import io
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "data"))

from airports import AIRPORTS

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "firmware", "sdpro-clock-weather"))
NL = chr(10)
BS = chr(92)


def coverage():
    """Every syllable the Small set can draw: the bundled font plus the extras."""
    s = io.open(ROOT + "/src/display/UiTextFont.cpp", encoding="utf-8").read()
    seg = s[s.index("SMALL_GLYPHS[] PROGMEM"):s.index("LARGE_GLYPHS[] PROGMEM")]
    have = set(int(m, 16) for m in re.findall(r"\{0x([0-9A-Fa-f]{4})u,", seg))
    x = io.open(ROOT + "/src/display/ExtraGlyphs.h", encoding="utf-8").read()
    have |= set(int(m, 16) for m in re.findall(r"\{0x([0-9A-Fa-f]{4})u,", x[x.index("ENTRIES_SMALL"):]))
    return have


def esc(text):
    return '"' + "".join(BS + "x%02x" % b for b in text.encode("utf-8")) + '"'


def main():
    # COUNT is emitted as uint8_t, and at 256 entries it wraps to zero:
    # every lookup then finds nothing and every label reverts to its raw
    # code, with no error anywhere. Refuse here so that day is a build
    # failure instead of a quiet regression.
    assert len(AIRPORTS) < 256, "table too large for uint8_t COUNT (%d)" % len(AIRPORTS)

    codes = [c for c, _ in AIRPORTS]
    dupes = sorted(set(c for c in codes if codes.count(c) > 1))
    if dupes:
        raise SystemExit("duplicate IATA codes: " + ", ".join(dupes))
    for code, name in AIRPORTS:
        if len(code) != 3 or not code.isupper() or not code.isalpha():
            raise SystemExit("bad IATA code: " + code)

    have = coverage()
    missing = {}
    for code, name in AIRPORTS:
        for ch in name:
            if ord(ch) not in have:
                missing.setdefault(ch, []).append(code)
    if missing:
        print("  %d syllables the Small set cannot draw:" % len(missing))
        print("  " + ", ".join("0x%04X" % ord(ch) for ch in sorted(missing)))
        for ch, who in sorted(missing.items()):
            print("    U+%04X %s  for %s" % (ord(ch), ch, ",".join(who)))
        raise SystemExit("bake these into ExtraGlyphs first")

    longest = max(len(n.encode("utf-8")) for _, n in AIRPORTS)
    widest = max(len(n) for _, n in AIRPORTS)
    print("  %d airports, longest name %d bytes / %d syllables"
          % (len(AIRPORTS), longest, widest))

    out = io.StringIO()
    out.write("// SPDX-License-Identifier: GPL-3.0-or-later" + NL)
    out.write("// Generated by scripts/gen_airports.py - do not edit by hand." + NL)
    out.write("//" + NL)
    out.write("// IATA airport code to the name to show. The route service answers with the" + NL)
    out.write("// three-letter code, which means nothing at a glance on a dial." + NL)
    out.write("//" + NL)
    out.write("// The names are PROGMEM and so is the table, and the lookup copies into the" + NL)
    out.write("// caller's buffer, for the same reason as Airlines.h: a PROGMEM table pointing" + NL)
    out.write("// at plain literals leaves the literals themselves in DRAM." + NL)
    out.write("//" + NL)
    out.write("// Airports absent from the list keep showing their bare IATA code, which is" + NL)
    out.write("// still useful and cannot be wrong." + NL)
    out.write("#pragma once" + NL + NL)
    out.write("#include <pgmspace.h>" + NL + "#include <cstdint>" + NL + "#include <cstring>" + NL + NL)
    out.write("namespace Airports {" + NL + NL)
    out.write("constexpr size_t MAX_NAME = %d;   // longest name plus its terminator" % (longest + 1) + NL + NL)

    for code, name in sorted(AIRPORTS):
        out.write("const char N_%s[] PROGMEM = %s;   // %s%s" % (code, esc(name), name, NL))

    out.write(NL + "struct Entry {" + NL + "    char code[4];" + NL)
    out.write("    const char* name;" + NL + "};" + NL + NL)
    out.write("const Entry TABLE[] PROGMEM = {" + NL)
    for code, name in sorted(AIRPORTS):
        out.write('    {"%s", N_%s},' % (code, code) + NL)
    out.write("};" + NL)
    out.write("constexpr uint8_t COUNT = %d;" % len(AIRPORTS) + NL + NL)

    out.write("// Fills `out` and returns true when the code is known; leaves it empty and" + NL)
    out.write("// returns false otherwise, which the caller shows as the bare IATA code." + NL)
    out.write("inline bool nameFor(const char* iata, char* out, size_t size) {" + NL)
    out.write("    if (out == nullptr || size == 0) return false;" + NL)
    out.write("    out[0] = 0;" + NL)
    out.write("    if (iata == nullptr) return false;" + NL)
    out.write("    for (uint8_t i = 0; i < 3; ++i) {" + NL)
    out.write("        if (iata[i] < 'A' || iata[i] > 'Z') return false;" + NL)
    out.write("    }" + NL)
    out.write("    if (iata[3] != 0) return false;" + NL)
    out.write("    for (uint8_t i = 0; i < COUNT; ++i) {" + NL)
    out.write("        Entry entry{};" + NL)
    out.write("        memcpy_P(&entry, &TABLE[i], sizeof(Entry));" + NL)
    out.write("        if (entry.code[0] != iata[0] || entry.code[1] != iata[1] ||" + NL)
    out.write("            entry.code[2] != iata[2]) {" + NL)
    out.write("            continue;" + NL)
    out.write("        }" + NL)
    out.write("        strncpy_P(out, entry.name, size - 1);" + NL)
    out.write("        out[size - 1] = 0;" + NL)
    out.write("        return true;" + NL)
    out.write("    }" + NL)
    out.write("    return false;" + NL)
    out.write("}" + NL + NL)
    out.write("}  // namespace Airports" + NL)

    dest = ROOT + "/src/display/Airports.h"
    io.open(dest, "w", encoding="utf-8", newline="").write(out.getvalue())
    print("  wrote", dest)


main()
