"""Emit the ICAO designator to airline name table.

Both the table and the strings it points at are PROGMEM, and the lookup copies
into a caller buffer. Mixing the two - a PROGMEM table holding pointers to plain
literals - happens to work only because the toolchain currently places
unqualified literals in DRAM; put them in flash and every match would fault on a
bus that does not allow byte reads.

Every syllable is checked against the font before a name is emitted, so a name
can never silently fall back to a different weight or go missing.
"""
import io
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "data"))

from rotorcraft import ROTORCRAFT as AIRLINES

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "firmware", "sdpro-clock-weather"))
NL = chr(10)
BS = chr(92)


def coverage():
    s = io.open(ROOT + "/src/display/UiTextFont.cpp", encoding="utf-8").read()
    seg = s[s.index("SMALL_GLYPHS[] PROGMEM"):s.index("LARGE_GLYPHS[] PROGMEM")]
    have = set(int(m, 16) for m in re.findall(r"\{0x([0-9A-Fa-f]{4})u,", seg))
    x = io.open(ROOT + "/src/display/ExtraGlyphs.h", encoding="utf-8").read()
    have |= set(int(m, 16) for m in re.findall(r"\{0x([0-9A-Fa-f]{4})u,", x[x.index("ENTRIES_SMALL"):]))
    return have


def esc(text):
    return '"' + "".join(BS + "x%02x" % b for b in text.encode("utf-8")) + '"'


def main():
    # COUNT is emitted as uint8_t, and at 256 entries it wraps to zero:
    # every lookup then finds nothing and every label reverts to its raw
    # code, with no error anywhere. Refuse here so that day is a build
    # failure instead of a quiet regression.
    assert len(AIRLINES) < 256, "table too large for uint8_t COUNT (%d)" % len(AIRLINES)

    have = coverage()
    missing = {}
    for code, name in AIRLINES:
        for ch in name:
            if ord(ch) not in have:
                missing.setdefault(ch, []).append(code)
    if missing:
        for ch, who in sorted(missing.items()):
            print("  MISSING U+%04X for %s" % (ord(ch), ",".join(who)))
        raise SystemExit("the font cannot render every name")

    longest = max(len(n.encode("utf-8")) for _, n in AIRLINES)
    print("  %d rotorcraft types, longest name %d bytes" % (len(AIRLINES), longest))

    out = io.StringIO()
    out.write("// SPDX-License-Identifier: GPL-3.0-or-later" + NL)
    out.write("// Generated by scripts/gen_airlines.py - do not edit by hand." + NL)
    out.write("//" + NL)
    out.write("// ICAO type designator to the rotorcraft name to show. A helicopter almost never" + NL)
    out.write("// carries an airline designator, so the line that names the carrier for an airliner" + NL)
    out.write("// names the machine instead. The feed gives the type code directly." + NL)
    out.write("//" + NL)
    out.write("// The names are PROGMEM and so is the table, and the lookup copies into the" + NL)
    out.write("// caller's buffer. A PROGMEM table pointing at plain literals would read the" + NL)
    out.write("// pointer correctly and then fault on dereference the day the toolchain puts" + NL)
    out.write("// those literals in flash." + NL)
    out.write("//" + NL)
    out.write("// Types absent from the list keep showing their bare code, which is still useful" + NL)
    out.write("// and cannot be wrong." + NL)
    out.write("#pragma once" + NL + NL)
    out.write("#include <pgmspace.h>" + NL + "#include <cstdint>" + NL + "#include <cstring>" + NL + NL)
    out.write("namespace Rotorcraft {" + NL + NL)
    out.write("constexpr size_t MAX_NAME = %d;   // longest name plus its terminator" % (longest + 1) + NL + NL)

    for code, name in sorted(AIRLINES):
        out.write("const char T_%s[] PROGMEM = %s;   // %s%s" % (code, esc(name), name, NL))

    out.write(NL + "struct Entry {" + NL + "    char code[5];" + NL)
    out.write("    const char* name;" + NL + "};" + NL + NL)
    out.write("const Entry TABLE[] PROGMEM = {" + NL)
    for code, name in sorted(AIRLINES):
        out.write('    {"%s", T_%s},' % (code, code) + NL)
    out.write("};" + NL)
    out.write("constexpr uint8_t COUNT = %d;" % len(AIRLINES) + NL + NL)

    out.write("// Fills `out` and returns true when the prefix is known; leaves it empty and" + NL)
    out.write("// returns false otherwise, which the caller shows as the bare type code." + NL)
    out.write("inline bool nameFor(const char* type, char* out, size_t size) {" + NL)
    out.write("    if (out == nullptr || size == 0) return false;" + NL)
    out.write("    out[0] = 0;" + NL)
    out.write("    if (type == nullptr) return false;" + NL)
    out.write("    for (uint8_t i = 0; i < COUNT; ++i) {" + NL)
    out.write("        Entry entry{};" + NL)
    out.write("        memcpy_P(&entry, &TABLE[i], sizeof(Entry));" + NL)
    out.write("        if (strcmp(entry.code, type) != 0) continue;" + NL)
    out.write("        strncpy_P(out, entry.name, size - 1);" + NL)
    out.write("        out[size - 1] = 0;" + NL)
    out.write("        return true;" + NL)
    out.write("    }" + NL)
    out.write("    return false;" + NL)
    out.write("}" + NL + NL)
    out.write("// Whether the table recognises this code, without copying the name. The" + NL)
    out.write("// parser asks this of every aircraft in a reply just to decide what to draw," + NL)
    out.write("// and a lookup that answers a question it was not asked is a lookup that" + NL)
    out.write("// says the wrong thing about its own purpose." + NL)
    out.write("inline bool knows(const char* type) {" + NL)
    out.write("    if (type == nullptr || type[0] == 0) return false;" + NL)
    out.write("    for (uint8_t i = 0; i < COUNT; ++i) {" + NL)
    out.write("        Entry entry{};" + NL)
    out.write("        memcpy_P(&entry, &TABLE[i], sizeof(Entry));" + NL)
    out.write("        if (strcmp(entry.code, type) == 0) return true;" + NL)
    out.write("    }" + NL)
    out.write("    return false;" + NL)
    out.write("}" + NL + NL)
    out.write("}  // namespace Rotorcraft" + NL)

    dest = ROOT + "/src/display/Rotorcraft.h"
    io.open(dest, "w", encoding="utf-8", newline="").write(out.getvalue())
    print("  wrote", dest)


main()
